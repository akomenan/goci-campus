export function getUniversityById(id: string): University | undefined {
  return universities.find((u) => u.id === id);
}

export function getSigleInitials(sigle: string): string {
  const cleaned = sigle.replace(/[^A-Za-zÀ-ÿ0-9]/g, '');
  if (cleaned.length <= 3) return cleaned.toUpperCase();
  return cleaned.slice(0, 3).toUpperCase();
}

export function formatPhoneDisplay(tel: string): string {
  const digits = tel.replace(/\D/g, '');
  if (digits.startsWith('225') && digits.length === 13) {
    const local = digits.slice(3);
    return `(+225) ${local.slice(0, 2)} ${local.slice(2, 4)} ${local.slice(4, 6)} ${local.slice(6, 8)} ${local.slice(8)}`;
  }
  return tel;
}

